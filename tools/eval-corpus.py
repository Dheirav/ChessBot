#!/usr/bin/env python3
"""Build the evaluation-error corpus from the reviewed game archive.

The repo can already tell whether an evaluation *changed* (tests/evalref) and
whether it is mirror-symmetric. Nothing could tell whether it got more
*accurate*, so eval work has only ever been answerable by playing games — hours
per verdict. This turns positions the engine has already misjudged in real
games into a file a test can score in seconds.

Two tags, and both matter:

  comp  the engine is materially ahead and the position is actually lost, or
        the reverse. This is BUGS.md 13: compensation the evaluation prices at
        zero. These are the positions a fix has to move.
  ctl   a deterministic sample of ordinary positions. A term that "fixes" comp
        by wrecking everything else has to be visible, or the corpus is a way
        to overfit rather than a way to measure.

Positions are filtered to quiet ones — not in check, and the best move is not a
capture, check or promotion. A static evaluation cannot be asked to agree with
a deep search where a tactic decides the position, and scoring it against one
would measure search depth wearing an evaluation's name.

Usage:  tools/eval-corpus.py [out.epd]      (default tests/data/evalerr.epd)
"""
import chess, chess.pgn, json, os, glob, sys

ME      = "Crimsy_Bot"
ARCHIVE = os.environ.get("ARCHIVE", "/home/dheirav/Code/lichess-bot/game_records")
RECORDS = os.path.expanduser("~/reviews/records")
OUT     = sys.argv[1] if len(sys.argv) > 1 else "tests/data/evalerr.epd"
CTL_STRIDE = 11          # fixed, not random: the corpus must rebuild identically
EVAL_CAP   = 1000        # beyond ±10 pawns both sides agree it is over
VALUE = {chess.PAWN: 100, chess.KNIGHT: 300, chess.BISHOP: 300,
         chess.ROOK: 500, chess.QUEEN: 900}

def material(board):
    w = sum(VALUE[p.piece_type] for p in board.piece_map().values()
            if p.color and p.piece_type != chess.KING)
    b = sum(VALUE[p.piece_type] for p in board.piece_map().values()
            if not p.color and p.piece_type != chess.KING)
    return w - b

def quiet(board, uci):
    """A position whose best continuation is not a tactic."""
    if board.is_check():
        return False
    if not uci:
        return True
    try:
        mv = chess.Move.from_uci(uci)
    except ValueError:
        return True
    if mv not in board.legal_moves:
        return False
    return not (board.is_capture(mv) or mv.promotion or board.gives_check(mv))

rows, seen, scanned = [], set(), 0
for pgn_path in sorted(glob.glob(os.path.join(ARCHIVE, "*.pgn"))):
    gid = os.path.basename(pgn_path)[:-4].split(" - ")[-1]
    rec_path = os.path.join(RECORDS, gid + ".json")
    if not os.path.exists(rec_path):
        continue
    rec = json.load(open(rec_path))
    if ME not in (rec["head"]["white"], rec["head"]["black"]):
        continue
    by_ply = {m["n"]: m for m in rec["moves"]}
    game = chess.pgn.read_game(open(pgn_path))
    if game is None:
        continue
    board = game.board()
    for i, move in enumerate(game.mainline_moves()):
        board.push(move)
        entry = by_ply.get(i)
        if entry is None:
            continue
        ev = entry["ev"]                      # Stockfish, white's point of view
        scanned += 1
        if abs(ev) > EVAL_CAP or not quiet(board, entry.get("best") or entry.get("uci")):
            continue
        fen = board.fen()
        key = " ".join(fen.split()[:4])       # ignore clocks: same position, same row
        if key in seen:
            continue
        mat = material(board)
        # Disagreement in *sign*, both sides of it meaningful: material says one
        # player is winning and the position says the other is.
        comp = (mat >= 100 and ev <= -100) or (mat <= -100 and ev >= 100)
        if comp:
            seen.add(key)
            rows.append((fen, ev, "comp", gid, i))
        elif scanned % CTL_STRIDE == 0:
            seen.add(key)
            rows.append((fen, ev, "ctl", gid, i))

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("# evaluation-error corpus -- generated by tools/eval-corpus.py, do not hand-edit\n")
    f.write("# <fen> ; sf <centipawns, white POV> ; tag <comp|ctl> ; id <game>:<ply>\n")
    for fen, ev, tag, gid, ply in rows:
        f.write(f"{fen} ; sf {ev} ; tag {tag} ; id {gid}:{ply}\n")
n_comp = sum(1 for r in rows if r[2] == "comp")
print(f"scanned {scanned} reviewed positions")
print(f"wrote {len(rows)} to {OUT}: {n_comp} comp, {len(rows) - n_comp} ctl")
